import assert from 'node:assert/strict';
import {getPresetDeck} from '@/lib/data/preset-decks-catalog';
import {loadBotProfile,compatibleBotProfile,satisfiesDeckRequirements} from '@/lib/duel/bot/deck-profile';
import {BotBrain} from '@/lib/duel/bot/bot-brain';
const deck=getPresetDeck('tcg-sdaz'),full=await loadBotProfile(deck,'tcg');
const needed=new Set(full.routes.flatMap(route=>route.deckRequirements.main.map(r=>r.code)));
const flex=deck.main.find(code=>!needed.has(code));assert.ok(flex);
const changed={...deck,main:deck.main.map(code=>code===flex?89631139:code)};
assert.equal(await loadBotProfile(changed,'tcg'),null,'assinatura exata continua sendo opção restrita');
const partial=await loadBotProfile(changed,'tcg',{allowPartial:true});
assert.equal(partial.id,full.id);assert.equal(partial.routes.length,full.routes.length);
assert.equal(partial.compatibility.mode,'partial');
assert.equal(new BotBrain({deck:changed,profile:partial,format:'tcg',partialProfiles:true}).planner.profile.routes.length,full.routes.length);
assert.equal(new BotBrain({deck:changed,profile:partial,format:'tcg'}).planner.profile,null,'não promove cobertura parcial sem habilitá-la');
const noKitt={...deck,main:deck.main.filter(code=>code!==45484331)};
const restricted=await loadBotProfile(noKitt,'tcg',{allowPartial:true});assert.ok(restricted);
assert.ok(restricted.routes.every(route=>!route.deckRequirements.main.some(r=>r.code===45484331)));
assert.ok(restricted.compatibility.disabledRoutes.length>0);
assert.ok(new BotBrain({deck:noKitt,profile:restricted,partialProfiles:true,format:'tcg'}).planner.profile.compatibility.disabledRoutes.length>0);
assert.equal(await loadBotProfile({...deck,main:deck.main.filter(code=>code!==68468459)},'tcg',{allowPartial:true}),null,'sem Albaz, nenhuma rota é compatível');
assert.equal(await loadBotProfile(deck,'goat',{allowPartial:true}),null);
const requirements={main:[{code:1,count:2}],extra:[],alternatives:[{zone:'main',codes:[2,3],minCount:1}],forbidden:[4]};
assert.equal(satisfiesDeckRequirements({main:[1,1,3],extra:[]},requirements),true);
assert.equal(satisfiesDeckRequirements({main:[1,3],extra:[]},requirements),false);
assert.equal(satisfiesDeckRequirements({main:[1,1,4],extra:[]},requirements),false);
assert.equal(compatibleBotProfile({...full,engineRequirements:undefined},changed,'tcg'),null,'nenhuma inferência por nome do arquétipo');
console.log(`✓ assinatura exata, flex, ${restricted.routes.length}/${full.routes.length} rotas sem Kitt, peça obrigatória, quantidades, substitutos e formato`);
